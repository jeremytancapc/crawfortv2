export function translateText(text: string, locale: Locale): string {
  return locale === "en" ? text : (TRANSLATIONS[locale][text] ?? text);
}

export function detectLocale(languageTags: readonly string[]): Locale {
  for (const languageTag of languageTags) {
    const language = languageTag.toLowerCase();
    if (language === "zh" || language.startsWith("zh-")) return "zh-CN";
    if (language === "ms" || language.startsWith("ms-")) return "ms";
    if (language === "en" || language.startsWith("en-")) return "en";
  }
  return "en";
}

export function isLocale(value: string | null): value is Locale {
  return value !== null && LOCALES.some((locale) => locale === value);
}
